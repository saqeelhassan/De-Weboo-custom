foreach (glob($root . '/*.php') as $file) {
    $name = basename($file);
    if (str_starts_with($name, 'build-')) {
        continue;
    }

    $content = file_get_contents($file);
    $original = $content;

    foreach ($replacements as $from => $to) {
        $content = str_replace($from, $to, $content);
    }

    if ($content !== $original) {
        file_put_contents($file, $content);
        echo "Updated: $name\n";
    }
}

foreach (['includes/footer.php', 'includes/header.php'] as $rel) {
    $file = $root . '/' . $rel;
    if (!is_file($file)) {
        continue;
    }
    $content = file_get_contents($file);
    $original = $content;
    foreach ($replacements as $from => $to) {
        $content = str_replace($from, $to, $content);
    }
    if ($content !== $original) {
        file_put_contents($file, $content);
        echo "Updated: $rel\n";
    }
}

